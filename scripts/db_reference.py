"""Print every table, column, key and index as Markdown, straight from the models.

DATABASE.md's reference section is this script's output, so it can't drift from the code:
    docker compose run --rm tools python scripts/db_reference.py > docs/db-reference.md
"""

import inspect

from sqlalchemy import Column, Index, Table
from sqlalchemy.dialects import postgresql
from sqlalchemy.sql.schema import ForeignKeyConstraint, UniqueConstraint

import ask_teach_chat.models
import eval_lab.models
import go_live.models
import knowledge_brain.models
import self_improve.models
from core.models import SCHEMAS, Base

MODULES = (
    knowledge_brain.models,
    ask_teach_chat.models,
    eval_lab.models,
    self_improve.models,
    go_live.models,
)
DIALECT = postgresql.dialect()  # type: ignore[no-untyped-call]


def table_docs() -> dict[str, str]:
    """Each model class's docstring, by its full table name."""
    docs: dict[str, str] = {}
    for mapper in Base.registry.mappers:
        table = mapper.local_table
        if isinstance(table, Table):
            doc = inspect.getdoc(mapper.class_) or ""
            docs[table.fullname] = " ".join(doc.split())
    return docs


def column_type(column: Column[object]) -> str:
    return str(column.type.compile(dialect=DIALECT)).lower()


def default(column: Column[object]) -> str:
    if column.computed is not None:
        return "computed"
    if column.server_default is not None:
        arg = getattr(column.server_default, "arg", "")
        return str(getattr(arg, "text", arg))
    return ""


def keys(column: Column[object]) -> str:
    parts: list[str] = []
    if column.primary_key:
        parts.append("PK")
    for fk in column.foreign_keys:
        target = fk.target_fullname
        parts.append(f"FK {target} ({fk.ondelete or 'no action'})")
    return ", ".join(parts)


def main() -> None:
    _ = MODULES
    docs = table_docs()
    print("<!-- Generated by scripts/db_reference.py from the models. Do not edit by hand. -->")
    for schema in SCHEMAS:
        tables = [t for t in Base.metadata.sorted_tables if t.schema == schema]
        print(f"\n### Schema `{schema}` ({len(tables)} tables)\n")
        for table in sorted(tables, key=lambda t: t.name):
            print(f"#### `{table.fullname}`\n")
            if docs.get(table.fullname):
                print(f"{docs[table.fullname]}\n")
            print("| Column | Type | Null | Default | Keys |")
            print("| --- | --- | --- | --- | --- |")
            for column in table.columns:
                null = "yes" if column.nullable else "no"
                print(
                    f"| {column.name} | {column_type(column)} | {null} | "
                    f"{default(column)} | {keys(column)} |"
                )
            extras: list[str] = []
            for constraint in table.constraints:
                if isinstance(constraint, UniqueConstraint):
                    cols = ", ".join(c.name for c in constraint.columns)
                    extras.append(f"unique ({cols})")
                elif isinstance(constraint, ForeignKeyConstraint) and len(constraint.columns) > 1:
                    extras.append(f"foreign key {constraint.name}")
            for index in sorted(table.indexes, key=lambda i: str(i.name)):
                extras.append(index_text(index))
            if extras:
                print("\nIndexes and constraints: " + "; ".join(extras) + ".")
            print()


def index_text(index: Index) -> str:
    cols = ", ".join(str(getattr(c, "name", c)) for c in index.expressions)
    using = index.dialect_options["postgresql"].get("using")
    where = index.dialect_options["postgresql"].get("where")
    text = f"`{index.name}` on ({cols})"
    if index.unique:
        text = "unique " + text
    if using:
        text += f" using {using}"
    if where is not None:
        text += f" where {where}"
    return text


if __name__ == "__main__":
    main()

# Row-level security (D1). Every table with a business_id column shows and accepts only
# the rows of the business set for the transaction. The owner role skips these policies
# (it owns the tables), which is why the app never connects as the owner.
RLS_SQL = """
DO $$
DECLARE
  t record;
BEGIN
  FOR t IN
    SELECT c.table_schema, c.table_name
    FROM information_schema.columns c
    JOIN information_schema.tables tb
      ON tb.table_schema = c.table_schema AND tb.table_name = c.table_name
    WHERE c.column_name = 'business_id'
      AND tb.table_type = 'BASE TABLE'
      AND c.table_schema IN ('core', 'brain', 'chat', 'evals', 'improve', 'golive')
      -- memberships has its own policy below; a browser session is looked up by its token
      AND (c.table_schema, c.table_name) NOT IN (('core', 'memberships'), ('core', 'web_sessions'))
  LOOP
    EXECUTE 'ALTER TABLE ' || quote_ident(t.table_schema) || '.' || quote_ident(t.table_name)
      || ' ENABLE ROW LEVEL SECURITY';
    EXECUTE 'CREATE POLICY tenant_isolation ON '
      || quote_ident(t.table_schema) || '.' || quote_ident(t.table_name)
      || ' USING (business_id = core.current_business())'
      || ' WITH CHECK (business_id = core.current_business())';
  END LOOP;
END
$$;

-- A user sees their own memberships (to list their businesses) and, inside a business,
-- that business's members
ALTER TABLE core.memberships ENABLE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON core.memberships
  USING (business_id = core.current_business() OR user_id = core.current_app_user())
  WITH CHECK (business_id = core.current_business());

-- A business row is visible inside that business, and to its members (the switcher)
ALTER TABLE core.businesses ENABLE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON core.businesses
  USING (
    id = core.current_business()
    OR id IN (SELECT m.business_id FROM core.memberships m
              WHERE m.user_id = core.current_app_user())
  )
  WITH CHECK (id = core.current_business());
"""

